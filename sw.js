const CACHE_NAME = 'lpdh-pwa-cache-v1';
const OFFLINE_URL = '/offline-index.php'; // Optional: could just be '/'

self.addEventListener('install', (event) => {
    event.waitUntil(
        caches.open(CACHE_NAME).then((cache) => {
            return cache.addAll([
                '/',
                'wp-content/themes/lpdh_wp/style.css',
                'wp-content/themes/lpdh_wp/assets/img/logo/logo-lpdh-transparent.png'
            ]).catch(err => console.log('PWA: Cache addAll failed', err));
        })
    );
});

self.addEventListener('activate', (event) => {
    event.waitUntil(
        caches.keys().then((cacheNames) => {
            return Promise.all(
                cacheNames.map((cacheName) => {
                    if (cacheName !== CACHE_NAME) {
                        return caches.delete(cacheName);
                    }
                })
            );
        })
    );
});

self.addEventListener('fetch', (event) => {
    if (event.request.mode === 'navigate') {
        event.respondWith(
            fetch(event.request).catch(() => {
                return caches.match('/');
            })
        );
    } else {
        event.respondWith(
            caches.match(event.request).then((response) => {
                return response || fetch(event.request);
            })
        );
    }
});
